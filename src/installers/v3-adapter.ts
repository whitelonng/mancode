  if (!/^[0-7][0-9A-HJKMNP-TV-Z]{25}$/.test(operationId)) {
    throw new Error('MANCODE_ADAPTER_UPGRADE_OPERATION_ID_INVALID');
  }
  const root = path.resolve(projectRoot);
