async function readAdapterTarget(
  root: string,
  target: V3AdapterFileTarget,
): Promise<string | null> {
  const filePath = v3AdapterTargetPath(root, target);
  const resolved = await writeThroughResolvedPath(root, filePath);
  if (resolved !== null) {
    // Write-through: the resolved path is already proven to be a regular
    // file inside the real project root.
    return readFile(resolved, 'utf8');
  }
  await assertAdapterPathSafe(root, filePath);
  try {
    const entry = await lstat(filePath);
    if (!entry.isFile() || entry.isSymbolicLink()) {
      throw new Error('MANCODE_ARTIFACT_PATH_UNSAFE');
    }
  } catch (error) {
    if (isNodeError(error) && error.code === 'ENOENT') return null;
    throw error;
  }
  return readFile(filePath, 'utf8');
}

function fixedAdapterTargetPaths(
  root: string,
  platform: PlatformName,
): string[] {
  const targets = new Set<string>([
    path.join(root, targetFor(platform)),
    ...V3_MODE_NAMES.map((mode) => v3ModeEntryPath(root, platform, mode)),
    ...legacyAdapterTargetsForPlatform(platform, true).map((target) =>
      v3AdapterTargetPath(root, target),
    ),
  ]);
  if (platform === 'claude-code' || platform === 'cursor') {
    for (const retired of retiredBootstrapSpecs(root, platform)) {
      targets.add(retired.filePath);
    }
  }
  return [...targets];
}

async function assertPlatformAdapterPathsSafe(
  root: string,
  platform: PlatformName,
): Promise<void> {
  for (const target of fixedAdapterTargetPaths(root, platform)) {
    await assertAdapterPathSafe(root, target);
  }
}

/** One unsafe fixed adapter path, reported without writing anything. */
export interface V3UnsafeAdapterPath {
  /** Absolute path of the offending entry. */
  target: string;
  /** Path relative to the project root. */
  relative: string;
  kind: 'symlink' | 'not-directory' | 'outside-root' | 'root-symlink';
  /** True when the entry is the final fixed target (a file), false for parents. */
  finalTarget: boolean;
  /** For symlinks: the resolved absolute path, or null when unresolvable. */
  resolvedTo: string | null;
  /** Project root used to constrain materialization of a resolved link. */
  projectRoot?: string;
}

/**
 * Reports every unsafe fixed adapter path for a platform without writing
 * anything, so interactive flows can offer a remediation before installing.
 */
export async function inspectUnsafeV3AdapterPaths(
  projectRoot: string,
  platform: PlatformName,
): Promise<V3UnsafeAdapterPath[]> {
  const root = path.resolve(projectRoot);
  const found: V3UnsafeAdapterPath[] = [];
  const seen = new Set<string>();
  for (const target of fixedAdapterTargetPaths(root, platform)) {
    if (seen.has(target)) continue;
    seen.add(target);
    const unsafe = await findUnsafeAdapterPathEntry(root, target);
    if (unsafe !== null) found.push(unsafe);
  }
  return found;
}

/**
 * Materializes fixable final-target symlinks as regular files that copy the
 * resolved content, so a confirmed init can continue without losing what the
 * link used to expose. Escaping parents and broken links are left untouched.
 */
export async function replaceUnsafeV3AdapterSymlinks(
  entries: readonly V3UnsafeAdapterPath[],
): Promise<void> {
  for (const entry of entries) {
    if (
      entry.kind !== 'symlink' ||
      !entry.finalTarget ||
      entry.resolvedTo === null
    ) {
      continue;
    }
    const projectRoot = entry.projectRoot;
    if (
      projectRoot === undefined ||
      (await relativeWithinRealRoot(projectRoot, entry.resolvedTo)) === null
    ) {
      continue;
    }
    const resolvedEntry = await lstat(entry.resolvedTo).catch(() => null);
    if (
      resolvedEntry === null ||
      !resolvedEntry.isFile() ||
      resolvedEntry.isSymbolicLink()
    )
      continue;
    const content = await readFile(entry.resolvedTo);
    await rm(entry.target, { force: true });
    await writeFile(entry.target, content);
  }
}

/** Rejects a symlink or non-directory in any fixed adapter path segment. */
async function assertAdapterPathSafe(
  root: string,
  target: string,
): Promise<void> {
  const unsafe = await findUnsafeAdapterPathEntry(root, target);
  if (unsafe === null) return;
  if (unsafe.kind === 'outside-root') {
    throw new Error(
      `MANCODE_ARTIFACT_PATH_UNSAFE: adapter target must stay inside the project root: ${target}`,
    );
  }
  if (unsafe.kind === 'root-symlink') {
    throw new Error(
      `MANCODE_ARTIFACT_PATH_UNSAFE: project root must be a real directory, not a symbolic link: ${root}`,
    );
  }
  if (unsafe.kind === 'not-directory') {
    throw new Error(
      `MANCODE_ARTIFACT_PATH_UNSAFE: ${unsafe.relative} cannot be used because ${path.basename(unsafe.target)} is not a directory`,
    );
  }
  // The one sanctioned link: a final target resolving to a regular file
  // inside the project root (CLAUDE.md -> AGENTS.md). Everything else is
  // still refused — mancode never writes through escaping or broken links.
  if (
    unsafe.finalTarget &&
    (await writeThroughResolvedPath(root, unsafe.target)) !== null
  ) {
    return;
  }
  const detail = unsafe.resolvedTo
    ? ` (resolves to ${unsafe.resolvedTo})`
    : ' (broken link)';
  const replacement = unsafe.finalTarget
    ? 'a regular file'
    : 'a real directory';
  throw new Error(
    `MANCODE_ARTIFACT_PATH_UNSAFE: ${unsafe.relative} is a symbolic link${detail}; mancode writes through a link only when it resolves to a regular file inside the project root. Replace it with ${replacement} before initializing the adapter.`,
  );
}

/** Finds the first unsafe entry in one fixed adapter path, or null when safe. */
async function findUnsafeAdapterPathEntry(
  root: string,
  target: string,
): Promise<V3UnsafeAdapterPath | null> {
  const relative = path.relative(root, target);
  if (!relative || relative.startsWith('..') || path.isAbsolute(relative)) {
    return {
      target,
      relative,
      kind: 'outside-root',
      finalTarget: false,
      resolvedTo: null,
      projectRoot: root,
    };
  }
  const rootEntry = await lstat(root);
  if (!rootEntry.isDirectory() || rootEntry.isSymbolicLink()) {
    return {
      target: root,
      relative,
      kind: 'root-symlink',
      finalTarget: false,
      resolvedTo: null,
      projectRoot: root,
    };
  }
  const segments = relative.split(path.sep);
  let current = root;
  for (let index = 0; index < segments.length; index += 1) {
    current = path.join(current, segments[index] ?? '');
    try {
      const entry = await lstat(current);
      if (entry.isSymbolicLink()) {
        return {
          target: current,
          relative,
          kind: 'symlink',
          finalTarget: index === segments.length - 1,
          resolvedTo: await resolveAdapterSymlinkForInspection(current),
          projectRoot: root,
        };
      }
      if (index < segments.length - 1 && !entry.isDirectory()) {
        return {
          target: current,
          relative,
          kind: 'not-directory',
          finalTarget: false,
          resolvedTo: null,
          projectRoot: root,
        };
      }
    } catch (error) {
      if (isNodeError(error) && error.code === 'ENOENT') return null;
      throw error;
    }
  }
  return null;
}

async function resolveAdapterSymlink(linkPath: string): Promise<string | null> {
  try {
    return await realpath(linkPath);
  } catch {
    return null;
  }
}

/** Resolves a link chain lexically so inspection can explain broken links. */
async function resolveAdapterSymlinkForInspection(
  linkPath: string,
): Promise<string | null> {
  let current = path.resolve(linkPath);
  const seen = new Set<string>();
  for (let depth = 0; depth < 40; depth += 1) {
    if (seen.has(current)) return null;
    seen.add(current);
    const entry = await lstatOrNullAdapter(current);
    if (entry === null) return current;
    if (!entry.isSymbolicLink()) {
      return (await realpath(current).catch(() => null)) ?? current;
    }
    let target: string;
    try {
      target = await readlink(current, 'utf8');
    } catch {
      return null;
    }
    current = path.resolve(
      path.isAbsolute(target)
        ? target
        : path.join(path.dirname(current), target),
    );
  }
  return null;
}

/**
 * When a fixed adapter target is a symlink that resolves to a regular file
 * inside the project root, mancode reads and writes through it — the
 * CLAUDE.md -> AGENTS.md convention. Returns the absolute resolved path, or
 * null when the entry is not such a link (broken, escaping, or non-regular).
 */
export async function writeThroughResolvedPath(
  root: string,
  target: string,
): Promise<string | null> {
  const entry = await lstat(target).catch((error) => {
    if (isNodeError(error) && error.code === 'ENOENT') return null;
    throw error;
  });
  if (entry === null || !entry.isSymbolicLink()) return null;
  const resolved = await resolveAdapterSymlink(target);
  if (resolved === null) return null;
  if ((await relativeWithinRealRoot(root, resolved)) === null) return null;
  const resolvedEntry = await lstat(resolved).catch(() => null);
  if (resolvedEntry === null || !resolvedEntry.isFile()) return null;
  return resolved;
}

/**
 * Relative path from the real root to an absolute resolved path, or null
 * when it escapes. realpath can add a /private prefix on macOS while
 * tmpdir() does not, so both sides are canonicalized before comparing.
 */
async function relativeWithinRealRoot(
  root: string,
  resolved: string,
): Promise<string | null> {
  const realRoot = await resolveAdapterSymlink(root);
  const base = realRoot ?? root;
  const relative = path.relative(base, resolved);
  if (!relative || relative.startsWith('..') || path.isAbsolute(relative)) {
    return null;
  }
  return relative;
}

/**
 * Physical write path for a fixed target: a write-through symlink writes its
 * resolved file so the link survives; everything else is the path itself.
 * Callers assert installability first, and this re-resolves right before
 * the write, so a link flipped between the two steps still cannot escape.
 */
async function writePathThrough(
  root: string,
  filePath: string,
): Promise<string> {
  return (await writeThroughResolvedPath(root, filePath)) ?? filePath;
}

async function removeManagedV3Block(
  filePath: string,
  startMarker: string,
  endMarker: string,
): Promise<void> {
  const existing = await readTextIfExists(filePath);
  if (existing === null || !hasManagedBlock(existing, startMarker, endMarker)) {
    return;
  }
  const cleaned = removeManagedBlock(existing, startMarker, endMarker);
  if (cleaned.trim()) {
    await atomicWrite(filePath, `${cleaned.trimEnd()}\n`);
  } else {
    await rm(filePath, { force: true });
  }
}

async function anyManagedBlockPresent(
  filePath: string,
  markerPairs: readonly (readonly [string, string])[],
): Promise<boolean> {
  const content = await readTextIfExists(filePath);
  return (
    content !== null &&
    markerPairs.some(([startMarker, endMarker]) =>
      hasManagedBlock(content, startMarker, endMarker),
    )
  );
}

async function readAdapterBytesIfExists(
  root: string,
  filePath: string,
): Promise<Buffer | null> {
  const resolved = await writeThroughResolvedPath(root, filePath);
  const readPath = resolved ?? filePath;
  if (resolved === null) {
    await assertAdapterPathSafe(root, filePath);
  }
  try {
    const entry = await lstat(readPath);
    if (!entry.isFile() || entry.isSymbolicLink()) {
      throw new Error('MANCODE_ARTIFACT_PATH_UNSAFE');
    }
  } catch (error) {
    if (isNodeError(error) && error.code === 'ENOENT') return null;
    throw error;
  }
  for (let attempt = 1; attempt <= ADAPTER_READ_MAX_ATTEMPTS; attempt += 1) {
    try {
      return await readFile(readPath);
    } catch (error) {
      if (isNodeError(error) && error.code === 'ENOENT') return null;
      if (
        !isRetriableAdapterReadError(error) ||
        attempt === ADAPTER_READ_MAX_ATTEMPTS
      ) {
        throw error;
      }
      await delay(ADAPTER_READ_RETRY_DELAY_MS * attempt);
    }
  }
  throw new Error('MANCODE_V3_ADAPTER_READ_RETRY_EXHAUSTED');
}

async function readTextIfExists(filePath: string): Promise<string | null> {
  for (let attempt = 1; attempt <= ADAPTER_READ_MAX_ATTEMPTS; attempt += 1) {
    try {
      return await readFile(filePath, 'utf8');
    } catch (error) {
      if (isNodeError(error) && error.code === 'ENOENT') return null;
      if (
        !isRetriableAdapterReadError(error) ||
        attempt === ADAPTER_READ_MAX_ATTEMPTS
      ) {
        throw error;
      }
      await delay(ADAPTER_READ_RETRY_DELAY_MS * attempt);
    }
  }
  throw new Error('MANCODE_V3_ADAPTER_READ_RETRY_EXHAUSTED');
}

async function atomicWrite(filePath: string, content: string): Promise<void> {
  const temporary = path.join(
    path.dirname(filePath),
    `.${path.basename(filePath)}.${process.pid}.${Date.now()}.tmp`,
  );
  try {
    await writeFile(temporary, content, { encoding: 'utf8', flag: 'wx' });
    await rename(temporary, filePath);
  } finally {
    await rm(temporary, { force: true }).catch(() => undefined);
  }
}

